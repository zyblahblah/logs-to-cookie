PASSWORD_NAME_HINTS = (
    "password",
    "passwords",
    "all passwords",
    "all_passwords",
    "passwordsall",
    "logins",
    "credentials",
)

URL_RE = re.compile(
    r"^(?:URL|HOST(?:NAME)?|SITE|SOFT\s*URL|ORIGIN|URL\s*\(form\)|URL\s*Origin)\s*[:=]\s*(.+)$",
    re.IGNORECASE,
)
USER_RE = re.compile(
    r"^(?:USER(?:NAME)?|LOGIN|EMAIL|USER\s*ID|USER\s*NAME)\s*[:=]\s*(.+)$",
    re.IGNORECASE,
)
PASS_RE = re.compile(
    r"^(?:PASS(?:WORD)?|PWD)\s*[:=]\s*(.+)$",
    re.IGNORECASE,
)
INLINE_ULP_RE = re.compile(
    r"^(?P<url>(?:https?|android)://[^/:\s]+(?::\d+)?(?:/[^\s:]*)?):"
    r"(?P<user>[^:\s]+):"
    r"(?P<pwd>.+)$"
)

NETSCAPE_HEADER = (
    "# Netscape HTTP Cookie File\n"
    "# https://curl.se/docs/http-cookies.html\n"
    "# Generated by logs-to-cookie. Do not edit.\n\n"
)


def domain_of(url: str) -> str:
    try:
        host = urlparse(url).hostname or ""
    except ValueError:
        host = ""
    return host.lower()


