#!/usr/bin/env python3
"""logs-to-cookie (single-file edition).

Sort and convert stealer-style log dumps into ULP and cookie formats.

No install needed — just::

    python logs_to_cookie.py --help
    python logs_to_cookie.py ulp     /path/to/logs -o creds.txt
    python logs_to_cookie.py cookies /path/to/logs -o cookies.txt
    python logs_to_cookie.py sort    /path/to/logs --keywords netflix,spotify -o sorted/

Stdlib only, Python 3.9+.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, Iterable, Iterator, List, Tuple
from urllib.parse import urlparse

__version__ = "0.2.0"

# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

PASSWORD_NAME_HINTS = (
    "password",
    "passwords",
    "all passwords",
    "all_passwords",
    "passwordsall",
    "logins",
    "credentials",
)

URL_RE = re.compile(
    r"^(?:URL|HOST(?:NAME)?|SITE|SOFT\s*URL|ORIGIN|URL\s*\(form\)|URL\s*Origin)\s*[:=]\s*(.+)$",
    re.IGNORECASE,
)
USER_RE = re.compile(
    r"^(?:USER(?:NAME)?|LOGIN|EMAIL|USER\s*ID|USER\s*NAME)\s*[:=]\s*(.+)$",
    re.IGNORECASE,
)
PASS_RE = re.compile(
    r"^(?:PASS(?:WORD)?|PWD)\s*[:=]\s*(.+)$",
    re.IGNORECASE,
)
INLINE_ULP_RE = re.compile(
    r"^(?P<url>(?:https?|android)://[^/:\s]+(?::\d+)?(?:/[^\s:]*)?):"
    r"(?P<user>[^:\s]+):"
    r"(?P<pwd>.+)$"
)

NETSCAPE_HEADER = (
    "# Netscape HTTP Cookie File\n"
    "# https://curl.se/docs/http-cookies.html\n"
    "# Generated by logs-to-cookie. Do not edit.\n\n"
)


def domain_of(url: str) -> str:
    try:
        host = urlparse(url).hostname or ""
    except ValueError:
        host = ""
    return host.lower()


# ---------------------------------------------------------------------------
# Credentials parsing
# ---------------------------------------------------------------------------


def _emit(cur: dict) -> Iterator[Tuple[str, str, str]]:
    if cur.get("url") and cur.get("user") is not None and cur.get("pwd") is not None:
        yield cur["url"], cur["user"], cur["pwd"]


def parse_credentials_text(text: str) -> Iterator[Tuple[str, str, str]]:
    """Yield ``(url, user, pwd)`` triples parsed from a credential dump."""
    cur: dict = {"url": None, "user": None, "pwd": None}

    for raw in text.splitlines():
        line = raw.strip().lstrip("\ufeff")
        if not line:
            yield from _emit(cur)
            cur = {"url": None, "user": None, "pwd": None}
            continue

        m = INLINE_ULP_RE.match(line)
        if m:
            yield m.group("url"), m.group("user"), m.group("pwd")
            cur = {"url": None, "user": None, "pwd": None}
            continue

        m = URL_RE.match(line)
        if m:
            yield from _emit(cur)
            cur = {"url": m.group(1).strip(), "user": None, "pwd": None}
            continue
        m = USER_RE.match(line)
        if m:
            cur["user"] = m.group(1).strip()
            continue
        m = PASS_RE.match(line)
        if m:
            cur["pwd"] = m.group(1).strip()
            if cur["url"] and cur["user"] is not None:
                yield cur["url"], cur["user"], cur["pwd"]
                cur = {"url": None, "user": None, "pwd": None}
            continue

    yield from _emit(cur)


def is_password_file(path: Path) -> bool:
    name = path.name.lower()
    if not name.endswith((".txt", ".log")):
        return False
    return any(hint in name for hint in PASSWORD_NAME_HINTS)


def iter_password_files(root: Path) -> Iterator[Path]:
    if root.is_file():
        if is_password_file(root):
            yield root
        return
    for path in root.rglob("*"):
        if path.is_file() and is_password_file(path):
            yield path


def collect_credentials(root: Path) -> Iterator[Tuple[str, str, str, Path]]:
    for path in iter_password_files(root):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for url, user, pwd in parse_credentials_text(text):
            yield url, user, pwd, path


# ---------------------------------------------------------------------------
# Cookie parsing / serialization
# ---------------------------------------------------------------------------


def parse_netscape(text: str) -> Iterator[Dict]:
    for raw in text.splitlines():
        if not raw.strip():
            continue
        line = raw
        if line.startswith("#HttpOnly_"):
            line = line[len("#HttpOnly_") :]
        elif line.lstrip().startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 7:
            continue
        domain, flag, path, secure, expires, name, value = parts
        try:
            exp_int = int(float(expires))
        except (TypeError, ValueError):
            exp_int = 0
        yield {
            "domain": domain,
            "hostOnly": flag.strip().upper() != "TRUE",
            "path": path or "/",
            "secure": secure.strip().upper() == "TRUE",
            "expires": exp_int,
            "name": name,
            "value": value,
        }


def parse_json_cookies(text: str) -> Iterator[Dict]:
    try:
        data = json.loads(text)
    except (json.JSONDecodeError, ValueError):
        return
    if isinstance(data, dict):
        if isinstance(data.get("cookies"), list):
            data = data["cookies"]
        else:
            data = [data]
    if not isinstance(data, list):
        return
    for entry in data:
        if not isinstance(entry, dict):
            continue
        domain = entry.get("domain") or entry.get("Domain") or entry.get("host") or ""
        if not domain:
            continue
        host_only = entry.get("hostOnly")
        if host_only is None:
            host_only = not str(domain).startswith(".")
        expires_raw = (
            entry.get("expirationDate")
            or entry.get("expires")
            or entry.get("Expires")
            or 0
        )
        try:
            expires = int(float(expires_raw))
        except (TypeError, ValueError):
            expires = 0
        yield {
            "domain": str(domain),
            "hostOnly": bool(host_only),
            "path": entry.get("path") or "/",
            "secure": bool(entry.get("secure", False)),
            "expires": expires,
            "name": entry.get("name", ""),
            "value": entry.get("value", ""),
        }


def to_netscape_line(cookie: Dict) -> str:
    domain = cookie.get("domain", "") or ""
    host_only = bool(cookie.get("hostOnly"))
    if host_only:
        if domain.startswith("."):
            domain = domain[1:]
        flag = "FALSE"
    else:
        if domain and not domain.startswith("."):
            domain = "." + domain
        flag = "TRUE"
    return "\t".join(
        [
            domain,
            flag,
            cookie.get("path") or "/",
            "TRUE" if cookie.get("secure") else "FALSE",
            str(int(cookie.get("expires") or 0)),
            cookie.get("name", "") or "",
            cookie.get("value", "") or "",
        ]
    )


def _looks_like_cookie_path(path: Path) -> bool:
    name = path.name.lower()
    if name.endswith((".txt", ".json")) and "cookie" in name:
        return True
    parents = {p.name.lower() for p in path.parents}
    if "cookies" in parents and path.suffix.lower() in {".txt", ".json", ""}:
        return True
    return False


def iter_cookie_files(root: Path) -> Iterator[Path]:
    if root.is_file():
        if _looks_like_cookie_path(root):
            yield root
        return
    for path in root.rglob("*"):
        if path.is_file() and _looks_like_cookie_path(path):
            yield path


def collect_cookies(root: Path) -> Iterator[Dict]:
    for path in iter_cookie_files(root):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if not text.strip():
            continue
        stripped = text.lstrip()
        if path.suffix.lower() == ".json" or stripped.startswith(("[", "{")):
            yielded = False
            for cookie in parse_json_cookies(text):
                yielded = True
                yield cookie
            if yielded:
                continue
        yield from parse_netscape(text)


def dedupe_cookies(cookies: Iterable[Dict]) -> List[Dict]:
    seen = set()
    out: List[Dict] = []
    for c in cookies:
        key = (c.get("domain", ""), c.get("path", ""), c.get("name", ""))
        if key in seen:
            continue
        seen.add(key)
        out.append(c)
    return out


# ---------------------------------------------------------------------------
# Sorter
# ---------------------------------------------------------------------------


def _safe_keyword(k: str) -> str:
    return "".join(c if c.isalnum() or c in "-_." else "_" for c in k.strip()) or "kw"


def sort_logs(
    root: Path, out_dir: Path, keywords: Iterable[str]
) -> Dict[str, Tuple[int, int]]:
    kws = [k.strip() for k in keywords if k and k.strip()]
    if not kws:
        return {}
    out_dir.mkdir(parents=True, exist_ok=True)

    ulp_handles: Dict[str, "object"] = {}
    cookie_handles: Dict[str, "object"] = {}
    seen_ulp = {k: set() for k in kws}
    seen_cookie = {k: set() for k in kws}
    counts = {k: [0, 0] for k in kws}

    try:
        for k in kws:
            slug = _safe_keyword(k)
            ulp_handles[k] = open(out_dir / f"{slug}.ulp.txt", "w", encoding="utf-8")
            cookie_handles[k] = open(
                out_dir / f"{slug}.cookies.txt", "w", encoding="utf-8"
            )
            cookie_handles[k].write(NETSCAPE_HEADER)

        for url, user, pwd, _ in collect_credentials(root):
            host = domain_of(url)
            haystack = (url + " " + host).lower()
            line = f"{url}:{user}:{pwd}"
            for k in kws:
                if k.lower() in haystack:
                    if line in seen_ulp[k]:
                        continue
                    seen_ulp[k].add(line)
                    ulp_handles[k].write(line + "\n")
                    counts[k][0] += 1

        for cookie in collect_cookies(root):
            domain = (cookie.get("domain") or "").lower()
            if not domain:
                continue
            line = to_netscape_line(cookie)
            for k in kws:
                if k.lower() in domain:
                    if line in seen_cookie[k]:
                        continue
                    seen_cookie[k].add(line)
                    cookie_handles[k].write(line + "\n")
                    counts[k][1] += 1
    finally:
        for f in ulp_handles.values():
            f.close()
        for f in cookie_handles.values():
            f.close()

    return {k: (counts[k][0], counts[k][1]) for k in kws}


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def _open_out(path: str):
    if path == "-":
        return sys.stdout, False
    p = Path(path)
    if p.parent and str(p.parent) not in ("", "."):
        p.parent.mkdir(parents=True, exist_ok=True)
    return open(p, "w", encoding="utf-8"), True


def cmd_ulp(args: argparse.Namespace) -> int:
    root = Path(args.input)
    if not root.exists():
        print(f"input not found: {root}", file=sys.stderr)
        return 2
    filters = [f.strip().lower() for f in (args.filter or "").split(",") if f.strip()]
    out, owned = _open_out(args.output)
    seen = set()
    count = 0
    try:
        for url, user, pwd, _ in collect_credentials(root):
            if filters:
                hay = (url + " " + domain_of(url)).lower()
                if not any(flt in hay for flt in filters):
                    continue
            line = f"{url}:{user}:{pwd}"
            if not args.no_dedupe:
                if line in seen:
                    continue
                seen.add(line)
            out.write(line + "\n")
            count += 1
    finally:
        if owned:
            out.close()
    print(f"wrote {count} ULP entries to {args.output}", file=sys.stderr)
    return 0


def cmd_cookies(args: argparse.Namespace) -> int:
    root = Path(args.input)
    if not root.exists():
        print(f"input not found: {root}", file=sys.stderr)
        return 2
    filters = [f.strip().lower() for f in (args.filter or "").split(",") if f.strip()]
    cookies: List[Dict] = []
    for cookie in collect_cookies(root):
        domain = (cookie.get("domain") or "").lower()
        if filters and not any(flt in domain for flt in filters):
            continue
        cookies.append(cookie)
    cookies = dedupe_cookies(cookies)

    out_path = Path(args.output)
    if out_path.parent and str(out_path.parent) not in ("", "."):
        out_path.parent.mkdir(parents=True, exist_ok=True)

    if args.format == "netscape":
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(NETSCAPE_HEADER)
            for c in cookies:
                f.write(to_netscape_line(c) + "\n")
    else:
        out_path.write_text(json.dumps(cookies, indent=2), encoding="utf-8")

    print(f"wrote {len(cookies)} cookies to {out_path}", file=sys.stderr)
    return 0


def cmd_sort(args: argparse.Namespace) -> int:
    root = Path(args.input)
    if not root.exists():
        print(f"input not found: {root}", file=sys.stderr)
        return 2
    keywords = [k.strip() for k in args.keywords.split(",") if k.strip()]
    if not keywords:
        print("provide --keywords", file=sys.stderr)
        return 2
    stats = sort_logs(root, Path(args.output), keywords)
    for k, (u, c) in stats.items():
        print(f"  {k}: {u} ulp, {c} cookies", file=sys.stderr)
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="logs_to_cookie.py",
        description="Sort and convert log dumps into ULP and cookie formats (single-file edition).",
    )
    p.add_argument("--version", action="version", version=__version__)
    sub = p.add_subparsers(dest="cmd", required=True)

    pu = sub.add_parser("ulp", help="extract URL:USER:PASS lines from log dumps")
    pu.add_argument("input", help="path to log directory or file")
    pu.add_argument("-o", "--output", default="-", help="output file (- for stdout)")
    pu.add_argument(
        "--filter",
        help="comma-separated keywords matched against URL/host (substring)",
    )
    pu.add_argument(
        "--no-dedupe", action="store_true", help="keep duplicate lines (default: dedupe)"
    )
    pu.set_defaults(func=cmd_ulp)

    pc = sub.add_parser("cookies", help="collect and normalize cookies")
    pc.add_argument("input", help="path to log directory or file")
    pc.add_argument("-o", "--output", required=True, help="output file path")
    pc.add_argument(
        "--format",
        choices=["netscape", "json"],
        default="netscape",
        help="output format (default: netscape cookies.txt)",
    )
    pc.add_argument(
        "--filter",
        help="comma-separated keywords matched against cookie domain (substring)",
    )
    pc.set_defaults(func=cmd_cookies)

    ps = sub.add_parser(
        "sort",
        help="bucket logs into per-keyword ULP + cookies files",
    )
    ps.add_argument("input", help="path to log directory")
    ps.add_argument("-o", "--output", required=True, help="output directory")
    ps.add_argument(
        "--keywords",
        required=True,
        help="comma-separated keywords (e.g. netflix,spotify,roblox)",
    )
    ps.set_defaults(func=cmd_sort)

    return p


def main(argv=None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
