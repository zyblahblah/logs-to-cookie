def parse_netscape(text: str) -> Iterator[Dict]:
    for raw in text.splitlines():
        if not raw.strip():
            continue
        line = raw
        if line.startswith("#HttpOnly_"):
            line = line[len("#HttpOnly_"):]
        elif line.lstrip().startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 7:
            continue
        domain, flag, path, secure, expires, name, value = parts
        try:
            exp_int = int(float(expires))
        except (TypeError, ValueError):
            exp_int = 0
        yield {
            "domain": domain,
            "hostOnly": flag.strip().upper() != "TRUE",
            "path": path or "/",
            "secure": secure.strip().upper() == "TRUE",
            "expires": exp_int,
            "name": name,
            "value": value,
        }


def parse_json_cookies(text: str) -> Iterator[Dict]:
    try:
        data = json.loads(text)
    except (json.JSONDecodeError, ValueError):
        return
    if isinstance(data, dict):
        if isinstance(data.get("cookies"), list):
            data = data["cookies"]
        else:
            data = [data]
    if not isinstance(data, list):
        return
    for entry in data:
        if not isinstance(entry, dict):
            continue
        domain = entry.get("domain") or entry.get("Domain") or entry.get("host") or ""
        if not domain:
            continue
        host_only = entry.get("hostOnly")
        if host_only is None:
            host_only = not str(domain).startswith(".")
        expires_raw = (
            entry.get("expirationDate")
            or entry.get("expires")
            or entry.get("Expires")
            or 0
        )
        try:
            expires = int(float(expires_raw))
        except (TypeError, ValueError):
            expires = 0
        yield {
            "domain": str(domain),
            "hostOnly": bool(host_only),
            "path": entry.get("path") or "/",
            "secure": bool(entry.get("secure", False)),
            "expires": expires,
            "name": entry.get("name", ""),
            "value": entry.get("value", ""),
        }


def to_netscape_line(cookie: Dict) -> str:
    domain = cookie.get("domain", "") or ""
    host_only = bool(cookie.get("hostOnly"))
    if host_only:
        if domain.startswith("."):
            domain = domain[1:]
        flag = "FALSE"
    else:
        if domain and not domain.startswith("."):
            domain = "." + domain
        flag = "TRUE"
    return "\t".join(
        [
            domain,
            flag,
            cookie.get("path") or "/",
            "TRUE" if cookie.get("secure") else "FALSE",
            str(int(cookie.get("expires") or 0)),
            cookie.get("name", "") or "",
            cookie.get("value", "") or "",
        ]
    )


def _looks_like_cookie_path(path: Path) -> bool:
    name = path.name.lower()
    if name.endswith((".txt", ".json")) and "cookie" in name:
        return True
    parents = {p.name.lower() for p in path.parents}
    if "cookies" in parents and path.suffix.lower() in {".txt", ".json", ""}:
        return True
    return False


def iter_cookie_files(root: Path) -> Iterator[Path]:
    if root.is_file():
        if _looks_like_cookie_path(root):
            yield root
        return
    for path in root.rglob("*"):
        if path.is_file() and _looks_like_cookie_path(path):
            yield path


def collect_cookies(root: Path) -> Iterator[Dict]:
    for cookie, _src in collect_cookies_with_source(root):
        yield cookie


def collect_cookies_with_source(root: Path) -> Iterator[Tuple[Dict, Path]]:
    """Yield ``(cookie, source_file)`` tuples."""
    for path in iter_cookie_files(root):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if not text.strip():
            continue
        stripped = text.lstrip()
        if path.suffix.lower() == ".json" or stripped.startswith(("[", "{")):
            yielded = False
            for cookie in parse_json_cookies(text):
                yielded = True
                yield cookie, path
            if yielded:
                continue
        for cookie in parse_netscape(text):
            yield cookie, path


_ARCHIVE_TEMPDIR_RE = re.compile(r"^x\d{3}_")


def source_name_for(path: Path, root: Path) -> str:
    """Derive a human-friendly ``source`` (usually victim) name for ``path``."""
    try:
        rel = path.resolve().relative_to(root.resolve())
    except ValueError:
        name = path.parent.name or "unknown"
        return _ARCHIVE_TEMPDIR_RE.sub("", name) or "unknown"

    parts = rel.parts
    if parts and parts[0].lower() in ("cookies", "cookie"):
        name = root.name or "unknown"
    elif parts:
        name = parts[0]
    else:
        name = root.name or "unknown"
    return _ARCHIVE_TEMPDIR_RE.sub("", name) or "unknown"


def safe_source_name(name: str) -> str:
    cleaned = "".join(
        c if c.isalnum() or c in '-_.[]()' else '_' for c in (name or '').strip()
    )
    return cleaned or "unknown"


def dedupe_cookies(cookies: Iterable[Dict]) -> List[Dict]:
    seen = set()
    out: List[Dict] = []
    for c in cookies:
        key = (c.get("domain", ""), c.get("path", ""), c.get("name", ""))
        if key in seen:
            continue
        seen.add(key)
        out.append(c)
    return out


# ---------------------------------------------------------------------------
# Archive extraction (supports .zip natively; .rar/.7z via system binaries)
# ---------------------------------------------------------------------------

ARCHIVE_EXTS = {".zip", ".rar", ".7z"}


def is_archive(path: Path) -> bool:
    return path.suffix.lower() in ARCHIVE_EXTS


def _have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def _seven_zip_binary() -> Optional[str]:
    for cand in ("7z", "7za", "7zz"):
        if _have(cand):
            return cand
    return None


def _try_zip(archive: Path, dest: Path, passwords: List[Optional[str]]) -> bool:
    """Try to extract a .zip archive, attempting each password in turn.

    FIX: Previously ``BadZipFile`` was caught and caused an immediate
    ``return False``, aborting all remaining password attempts. Some
    Python versions raise ``BadZipFile`` instead of ``RuntimeError`` on
    a wrong password, so we now ``continue`` to the next password instead.
    """
    try:
        zf = zipfile.ZipFile(archive)
    except (zipfile.BadZipFile, OSError):
        return False
    try:
        for pwd in passwords:
            pwd_b = pwd.encode("utf-8") if pwd else None
            try:
                zf.extractall(dest, pwd=pwd_b)
                return True
            except RuntimeError:
                # Wrong password — try the next one.
                continue
            except zipfile.BadZipFile:
                # BUG FIX: Some Python builds raise BadZipFile for wrong
                # passwords; continue trying instead of giving up entirely.
                continue
    finally:
        zf.close()
    return False


def _try_7z(archive: Path, dest: Path, passwords: List[Optional[str]]) -> bool:
    binary = _seven_zip_binary()
    if not binary:
        return False
    for pwd in passwords:
        cmd = [binary, "x", "-y", f"-o{dest}"]
        # BUG FIX: f"-p{pwd}" breaks for passwords containing special chars
        # like "://" (URL-style passwords). subprocess doesn't use a shell so
        # no shell escaping is needed — but 7z itself can misparse the value
        # when it contains colon/slash sequences in the combined flag form.
        # Appending as a separate element is identical to 7z but avoids the
        # ambiguity. Also capture stdout/stderr instead of DEVNULL so errors
        # are visible in Railway logs for debugging.
        cmd.append(f"-p{pwd}" if pwd is not None else "-p")
        cmd.append(str(archive))
        try:
            result = subprocess.run(
                cmd,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=600,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if result.returncode == 0:
            return True
    return False


def _try_unrar(archive: Path, dest: Path, passwords: List[Optional[str]]) -> bool:
    if not _have("unrar"):
        return False
    for pwd in passwords:
        cmd = ["unrar", "x", "-y", "-inul"]
        cmd.append(f"-p{pwd}" if pwd is not None else "-p-")
        cmd.append(str(archive))
        cmd.append(str(dest) + os.sep)
        try:
            result = subprocess.run(
                cmd,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=600,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if result.returncode == 0:
            return True
    return False


def extract_archive(archive: Path, dest: Path, passwords: List[Optional[str]]) -> bool:
    """Extract ``archive`` into ``dest``, trying each password in turn.

    Returns ``True`` on success, ``False`` if no password worked or a
    required binary (``unrar``, ``7z``) is not installed.
    """
    dest.mkdir(parents=True, exist_ok=True)
    ext = archive.suffix.lower()
    if ext == ".zip":
        if _try_zip(archive, dest, passwords):
            return True
        return _try_7z(archive, dest, passwords)
    if ext == ".rar":
        if _try_unrar(archive, dest, passwords):
            return True
        return _try_7z(archive, dest, passwords)
    if ext == ".7z":
        return _try_7z(archive, dest, passwords)
    return False


def expand_input(
    inputs: Iterable[Path],
    passwords: Iterable[str],
    workdir: Path,
    recurse: bool = True,
) -> Tuple[List[Path], List[Path]]:
    """Resolve a mix of directories and archives into extraction roots.

    Returns ``(roots, failures)`` where ``failures`` is a list of archives
    that could not be extracted (wrong password, missing binary, corruption).
    """
    pwd_list: List[Optional[str]] = [None]
    for p in passwords:
        if p and p not in pwd_list:
            pwd_list.append(p)

    workdir.mkdir(parents=True, exist_ok=True)
    roots: List[Path] = []
    failures: List[Path] = []
    queue: List[Path] = []
    seen: set = set()

    for inp in inputs:
        inp = inp.resolve()
        if inp.is_file() and is_archive(inp):
            queue.append(inp)
        else:
            roots.append(inp)

    counter = 0
    while queue:
        archive = queue.pop()
        if archive in seen:
            continue
        seen.add(archive)
        counter += 1
        safe = "".join(c if c.isalnum() or c in "-_." else "_" for c in archive.stem)
        target = workdir / f"x{counter:03d}_{safe or 'arch'}"
        if extract_archive(archive, target, pwd_list):
            roots.append(target)
            if recurse:
                for nested in target.rglob("*"):
                    if nested.is_file() and is_archive(nested) and nested not in seen:
                        queue.append(nested)
        else:
            failures.append(archive)

    return roots, failures


