"""logs-to-cookie (single-file edition).

Sort and convert stealer-style log dumps into ULP and cookie formats.

No install needed — just::

    python logs_to_cookie.py --help
    python logs_to_cookie.py ulp     /path/to/logs -o creds.txt
    python logs_to_cookie.py cookies /path/to/logs -o cookies.txt
    python logs_to_cookie.py sort    /path/to/logs --keywords netflix,spotify -o sorted/

Stdlib only, Python 3.9+.
"""

