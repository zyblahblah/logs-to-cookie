def _resolve_roots(
    stack: contextlib.ExitStack,
    input_path: str,
    passwords: List[str],
    *,
    workers: int = 4,
) -> Tuple[List[Path], List[Path]]:
    """Resolve ``input_path`` into extraction roots.

    If ``input_path`` is an HTTP(S) URL, the file is downloaded first.
    Archives are extracted using each supplied password in turn.

    Returns ``(roots, failures)``.
    """
    workdir: Optional[Path] = None
    if is_url(input_path):
        workdir = Path(
            stack.enter_context(tempfile.TemporaryDirectory(prefix="l2c-dl-"))
        )
        inp = download_to_workdir(input_path, workdir, workers=workers)
    else:
        inp = Path(input_path)
        if not inp.exists():
            return [], []

    do_extract = bool(passwords) or (inp.is_file() and is_archive(inp))
    if not do_extract:
        return [inp], []

    if workdir is None:
        workdir = Path(
            stack.enter_context(tempfile.TemporaryDirectory(prefix="l2c-"))
        )

    inputs: List[Path] = []
    if inp.is_file():
        inputs.append(inp)
    else:
        inputs.append(inp)
        for child in inp.rglob("*"):
            if child.is_file() and is_archive(child):
                inputs.append(child)

    with _Heartbeat("Extracting archive...", inp.name):
        return expand_input(inputs, passwords, workdir)


def _report_failures(failures: List[Path]) -> None:
    if not failures:
        return
    print(
        f"warning: {len(failures)} archive(s) could not be extracted "
        f"(wrong password or missing tool):",
        file=sys.stderr,
    )
    for f in failures[:10]:
        print(f"  - {f}", file=sys.stderr)
    if len(failures) > 10:
        print(f"  ... and {len(failures) - 10} more", file=sys.stderr)


