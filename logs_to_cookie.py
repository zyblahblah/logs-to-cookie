def _ask(prompt: str, default: Optional[str] = None) -> str:
    suffix = f" [{default}]" if default else ""
    try:
        answer = input(f"{prompt}{suffix}: ").strip()
    except EOFError:
        return default or ""
    if not answer and default is not None:
        return default
    return answer


def _ask_workers(inp: str) -> int:
    if not is_url(inp):
        return 4
    raw = _ask(
        "Parallel download workers for URL (1 = single stream)", default="4"
    )
    try:
        return max(1, int(raw))
    except ValueError:
        return 4


def _ask_passwords() -> List[str]:
    raw = _ask(
        "Archive password(s), comma-separated (leave blank if none)", default=""
    )
    if not raw:
        return []
    return [p.strip() for p in raw.split(",") if p.strip()]


def _ask_nonempty(prompt: str, default: Optional[str] = None) -> str:
    while True:
        val = _ask(prompt, default=default)
        if val:
            return val
        print("  (required)")


def _build_args(**kwargs) -> argparse.Namespace:
    ns = argparse.Namespace()
    for k, v in kwargs.items():
        setattr(ns, k, v)
    return ns


def run_interactive() -> int:
    """Simple menu-driven flow used when the script is run with no args.

    Designed for Termux / mobile "run this file" launchers where you don't
    have a persistent shell to pass CLI flags.
    """
    print("=" * 52)
    print(f" logs-to-cookie v{__version__} — interactive mode")
    print("=" * 52)
    print(" 1) ulp      — extract URL:USER:PASS")
    print(" 2) cookies  — build cookies.txt / JSON")
    print(" 3) sort     — bucket by keyword (ULP + cookies per keyword)")
    print(" q) quit")
    print()

    try:
        choice = _ask("Choose [1/2/3/q]", default="3").lower()
    except KeyboardInterrupt:
        print()
        return 0

    if choice in ("q", "quit", "exit"):
        return 0

    try:
        if choice in ("1", "ulp"):
            inp = _ask_nonempty("Input path or http(s) URL (dir, file, .zip/.rar/.7z)")
            passwords = _ask_passwords()
            workers = _ask_workers(inp)
            filt = _ask("Filter keywords (substring, comma-separated; blank=all)", default="")
            out = _ask("Output file (- for stdout)", default="creds.ulp.txt")
            return cmd_ulp(
                _build_args(
                    input=inp,
                    output=out,
                    filter=filt or None,
                    no_dedupe=False,
                    password=passwords,
                    workers=workers,
                )
            )

        if choice in ("2", "cookies"):
            inp = _ask_nonempty("Input path or http(s) URL (dir, file, .zip/.rar/.7z)")
            passwords = _ask_passwords()
            workers = _ask_workers(inp)
            filt = _ask(
                "Filter keywords (cookie domain substring; blank=all)", default=""
            )
            fmt_choice = _ask("Format [1=netscape, 2=json]", default="1")
            fmt = "json" if fmt_choice.strip() in ("2", "json") else "netscape"
            per_src_ans = _ask(
                "One folder per source/victim? [Y/n]", default="y"
            ).lower()
            per_source = per_src_ans not in ("n", "no", "0", "false")
            if per_source:
                out = _ask("Output directory", default="cookies_out")
            else:
                default_out = "cookies.txt" if fmt == "netscape" else "cookies.json"
                out = _ask("Output file", default=default_out)
            return cmd_cookies(
                _build_args(
                    input=inp,
                    output=out,
                    format=fmt,
                    filter=filt or None,
                    per_source=per_source,
                    password=passwords,
                    workers=workers,
                )
            )

        if choice in ("3", "sort"):
            inp = _ask_nonempty("Input path or http(s) URL (dir, file, .zip/.rar/.7z)")
            passwords = _ask_passwords()
            workers = _ask_workers(inp)
            keywords = _ask_nonempty(
                "Keywords to sort by (comma-separated, e.g. netflix,spotify,roblox)"
            )
            per_src_ans = _ask(
                "One folder per victim with a hit (victim/cookies.txt)? [Y/n]",
                default="y",
            ).lower()
            per_source = per_src_ans not in ("n", "no", "0", "false")
            out = _ask("Output directory", default="sorted")
            return cmd_sort(
                _build_args(
                    input=inp,
                    output=out,
                    keywords=keywords,
                    per_source=per_source,
                    password=passwords,
                    workers=workers,
                )
            )
    except KeyboardInterrupt:
        print("\naborted")
        return 130

    print(f"unknown choice: {choice!r}")
    return 2


def main(argv=None) -> int:
    # Drop into the interactive menu when no arguments were given (e.g. when
    # the script is run by a mobile launcher that just double-taps the file).
    if argv is None:
        argv = sys.argv[1:]
    if not argv:
        return run_interactive()

    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
